document.addEventListener('DOMContentLoaded', () => {
  if (document.body.dataset.servicePage === 'true') return;

  document.body.classList.add('js-ready');
  const year = document.getElementById('year');
  if (year) year.textContent = String(new Date().getFullYear());

  const translatable = [...document.querySelectorAll('[data-i18n]')];
  const englishDefaults = new Map(translatable.map((node) => [node, node.innerHTML]));
  const languageButtons = document.querySelectorAll('[data-lang]');
  const menuButton = document.querySelector('.menu-toggle');
  const navigation = document.querySelector('.primary-navigation');
  const reducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;

  const setLanguage = (language) => {
    const isArabic = language === 'ar';
    document.documentElement.lang = isArabic ? 'ar' : 'en';
    document.documentElement.dir = isArabic ? 'rtl' : 'ltr';
    translatable.forEach((node) => {
      const key = node.dataset.i18n;
      if (isArabic && arabic[key]) node.innerHTML = arabic[key];
      else node.innerHTML = englishDefaults.get(node) || '';
    });
    document.querySelectorAll('[data-i18n-aria]').forEach((node) => {
      const key = node.dataset.i18nAria;
      if (isArabic && arabic[key]) node.setAttribute('aria-label', arabic[key]);
      else if (key === 'menuOpen' || key === 'menuClose') {
        const expanded = menuButton?.getAttribute('aria-expanded') === 'true';
        node.setAttribute('aria-label', expanded ? 'Close navigation' : 'Open navigation');
      } else if (key === 'scrollCue') {
        node.setAttribute('aria-label', isArabic ? arabic.scrollCue : 'Scroll to services');
      } else if (key === 'mapAlt') {
        node.setAttribute('aria-label', isArabic ? arabic.mapAlt : 'Map illustration indicating Dammam, Saudi Arabia');
      }
    });
    languageButtons.forEach((button) => {
      button.setAttribute('aria-pressed', String(button.dataset.lang === language));
    });
  };

  languageButtons.forEach((button) => {
    button.addEventListener('click', () => setLanguage(button.dataset.lang));
  });

  const closeMenu = () => {
    if (!menuButton || !navigation) return;
    menuButton.setAttribute('aria-expanded', 'false');
    menuButton.setAttribute('aria-label', document.documentElement.lang === 'ar' ? arabic.menuOpen : 'Open navigation');
    navigation.classList.remove('is-open');
  };

  menuButton?.addEventListener('click', () => {
    const isOpen = menuButton.getAttribute('aria-expanded') !== 'true';
    menuButton.setAttribute('aria-expanded', String(isOpen));
    menuButton.setAttribute('aria-label', isOpen ? (document.documentElement.lang === 'ar' ? arabic.menuClose : 'Close navigation') : (document.documentElement.lang === 'ar' ? arabic.menuOpen : 'Open navigation'));
    navigation?.classList.toggle('is-open', isOpen);
  });

  navigation?.querySelectorAll('a').forEach((link) => link.addEventListener('click', closeMenu));
  document.addEventListener('keydown', (event) => {
    if (event.key === 'Escape') closeMenu();
  });

  const header = document.getElementById('site-header');
  const updateHeader = () => header?.classList.toggle('is-scrolled', window.scrollY > 12);
  updateHeader();
  window.addEventListener('scroll', updateHeader, { passive: true });

  const revealItems = document.querySelectorAll('.reveal');
  if (reducedMotion || !('IntersectionObserver' in window)) {
    revealItems.forEach((item) => item.classList.add('is-visible'));
  } else {
    const revealObserver = new IntersectionObserver((entries, observer) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add('is-visible');
          observer.unobserve(entry.target);
        }
      });
    }, { threshold: 0.12, rootMargin: '0px 0px -30px 0px' });
    revealItems.forEach((item) => revealObserver.observe(item));
  }

  document.querySelectorAll('.faq-question').forEach((button) => {
    button.addEventListener('click', () => {
      const isExpanded = button.getAttribute('aria-expanded') === 'true';
      const answer = document.getElementById(button.getAttribute('aria-controls'));
      if (!answer) return;

      button.setAttribute('aria-expanded', String(!isExpanded));
      if (isExpanded) {
        answer.classList.remove('is-open');
        window.setTimeout(() => { answer.hidden = true; }, reducedMotion ? 0 : 230);
      } else {
        answer.hidden = false;
        requestAnimationFrame(() => answer.classList.add('is-open'));
      }
    });
  });

  setLanguage('en');
});
